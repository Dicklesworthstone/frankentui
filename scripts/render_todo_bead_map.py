#!/usr/bin/env python3
"""Render or verify docs/main-todo-bead-map.md against .beads/issues.jsonl."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_MAP = ROOT / "docs" / "main-todo-bead-map.md"
DEFAULT_JSONL = ROOT / ".beads" / "issues.jsonl"

HEADER_PREFIX = "Generated by scripts/render_todo_bead_map.py on "
HEADER_RE = re.compile(
    r"^Generated by scripts/render_todo_bead_map\.py on \d{4}-\d{2}-\d{2} "
    r"from \.beads/issues\.jsonl \(sha256 [0-9a-f]{64}\); do not edit by hand$"
)
ITEM_RE = re.compile(r"^(\s*-\s*)\[[ x~?]\](\s+.*)$")
RANGE_RE = re.compile(r"\b(bd-[a-z0-9.]+)\.(\d+)\.\.(bd-[a-z0-9.]+)\.(\d+)\b")
BEAD_ID_RE = re.compile(r"\bbd-[a-z0-9]+(?:[.-][a-z0-9]+)*\b")


def load_beads(jsonl_path: Path) -> tuple[dict[str, str], str]:
    raw = jsonl_path.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    statuses: dict[str, str] = {}
    for line in raw.decode("utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        obj = json.loads(line)
        bead_id = obj.get("id")
        status = obj.get("status")
        if isinstance(bead_id, str) and isinstance(status, str):
            statuses[bead_id] = status
    return statuses, digest


def extract_bead_ids(text: str) -> list[str]:
    expanded_ranges: list[str] = []

    def _replace_range(match: re.Match[str]) -> str:
        prefix_a, start_s, prefix_b, end_s = match.groups()
        start = int(start_s)
        end = int(end_s)
        if prefix_a == prefix_b and start <= end and (end - start) <= 100:
            for idx in range(start, end + 1):
                expanded_ranges.append(f"{prefix_a}.{idx}")
            return " "
        return match.group(0)

    scrubbed = RANGE_RE.sub(_replace_range, text)
    direct = BEAD_ID_RE.findall(scrubbed)
    seen: set[str] = set()
    ordered: list[str] = []
    for bead_id in [*direct, *expanded_ranges]:
        if bead_id not in seen:
            seen.add(bead_id)
            ordered.append(bead_id)
    return ordered


def render_map_text(
    source_text: str,
    statuses: dict[str, str],
    jsonl_sha256: str,
    date_str: str,
) -> tuple[str, dict[str, object]]:
    lines = source_text.splitlines()
    generated_line = (
        f"{HEADER_PREFIX}{date_str} from .beads/issues.jsonl "
        f"(sha256 {jsonl_sha256}); do not edit by hand"
    )

    body_lines: list[str] = []
    skip_unresolved_section = False
    for line in lines:
        if line.startswith("## Unresolved IDs"):
            skip_unresolved_section = True
            continue
        if skip_unresolved_section:
            if line.startswith("## "):
                skip_unresolved_section = False
            else:
                continue
        if HEADER_RE.match(line.strip()):
            continue
        body_lines.append(line)

    out_lines: list[str] = []
    inserted_header = False
    items = 0
    checked = 0
    partial = 0
    unchecked = 0
    unresolved_items = 0
    unresolved_ids: list[str] = []

    for line in body_lines:
        if not inserted_header and line.startswith("# "):
            out_lines.append(line)
            out_lines.append("")
            out_lines.append(generated_line)
            inserted_header = True
            continue

        if inserted_header and len(out_lines) == 3 and line.strip() == "":
            continue

        item_match = ITEM_RE.match(line)
        if item_match and ("→" in line or "->" in line):
            prefix, rest = item_match.groups()
            bead_ids = extract_bead_ids(rest)
            items += 1
            if not bead_ids:
                mark = "?"
                unresolved_items += 1
            else:
                missing = [bid for bid in bead_ids if bid not in statuses]
                present = [bid for bid in bead_ids if bid in statuses]
                for bid in missing:
                    if bid not in unresolved_ids:
                        unresolved_ids.append(bid)
                if not present:
                    mark = "?"
                    unresolved_items += 1
                else:
                    closed_count = sum(1 for bid in present if statuses[bid] == "closed")
                    if closed_count == len(bead_ids) and not missing:
                        mark = "x"
                        checked += 1
                    elif closed_count > 0:
                        mark = "~"
                        partial += 1
                    else:
                        mark = " "
                        unchecked += 1
            out_lines.append(f"{prefix}[{mark}]{rest}")
        elif item_match:
            prefix, rest = item_match.groups()
            out_lines.append(f"{prefix}[x]{rest}")
        else:
            out_lines.append(line)

    if unresolved_ids:
        if out_lines and out_lines[-1].strip() != "":
            out_lines.append("")
        out_lines.append("## Unresolved IDs")
        for bid in unresolved_ids:
            out_lines.append(f"- `{bid}`")

    rendered = "\n".join(out_lines) + "\n"
    summary: dict[str, object] = {
        "items": items,
        "checked": checked,
        "partial": partial,
        "unchecked": unchecked,
        "unresolved": len(unresolved_ids),
        "unresolved_items": unresolved_items,
        "jsonl_sha256": jsonl_sha256,
    }
    return rendered, summary


def normalize_for_check(text: str) -> list[str]:
    normalized: list[str] = []
    for line in text.splitlines():
        if HEADER_RE.match(line.strip()):
            normalized.append("<GENERATED_HEADER>")
        else:
            normalized.append(line)
    return normalized


def run_self_test() -> int:
    sample_jsonl = "\n".join(
        [
            json.dumps({"id": "bd-1", "status": "closed"}),
            json.dumps({"id": "bd-2.1", "status": "closed"}),
            json.dumps({"id": "bd-2.2", "status": "open"}),
            json.dumps({"id": "bd-3", "status": "in_progress"}),
        ]
    )
    digest = hashlib.sha256(sample_jsonl.encode("utf-8")).hexdigest()
    statuses = {"bd-1": "closed", "bd-2.1": "closed", "bd-2.2": "open", "bd-3": "in_progress"}
    sample_map = (
        "# Sample Map\n\n"
        "## A) Section\n"
        "- [ ] Item one → bd-1\n"
        "- [ ] Item two → bd-2.1..bd-2.2\n"
        "- [x] Item three → bd-3\n"
        "- [ ] Item missing → bd-999\n"
    )
    rendered, summary = render_map_text(sample_map, statuses, digest, "2026-10-16")
    assert "- [x] Item one → bd-1" in rendered, rendered
    assert "- [~] Item two → bd-2.1..bd-2.2" in rendered, rendered
    assert "- [ ] Item three → bd-3" in rendered, rendered
    assert "- [?] Item missing → bd-999" in rendered, rendered
    assert "## Unresolved IDs\n- `bd-999`" in rendered, rendered
    assert summary["items"] == 4, summary
    assert summary["checked"] == 1, summary
    assert summary["partial"] == 1, summary
    assert summary["unchecked"] == 1, summary
    assert summary["unresolved"] == 1, summary
    print(json.dumps({"self_test": "passed", **summary}, sort_keys=True))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--map", type=Path, default=DEFAULT_MAP, help="Path to markdown map")
    parser.add_argument("--jsonl", type=Path, default=DEFAULT_JSONL, help="Path to issues.jsonl")
    parser.add_argument("--check", action="store_true", help="Verify map is up to date")
    parser.add_argument("--self-test", action="store_true", help="Run internal self-test")
    args = parser.parse_args()

    if args.self_test:
        return run_self_test()

    statuses, digest = load_beads(args.jsonl)
    current_text = args.map.read_text(encoding="utf-8")
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    rendered, summary = render_map_text(current_text, statuses, digest, today)

    if args.check:
        has_header = any(HEADER_RE.match(line.strip()) for line in current_text.splitlines())
        if not has_header or normalize_for_check(current_text) != normalize_for_check(rendered):
            summary["status"] = "stale"
            print(json.dumps(summary, sort_keys=True))
            return 1
        summary["status"] = "ok"
        print(json.dumps(summary, sort_keys=True))
        return 0

    args.map.write_text(rendered, encoding="utf-8")
    summary["status"] = "updated"
    print(json.dumps(summary, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
